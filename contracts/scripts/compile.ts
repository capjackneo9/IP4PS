/**
 * Compiles contracts/IP4PSRegistry.sol with the bundled solc-js compiler (no compiler download needed)
 * and writes:
 *   contracts/artifacts/IP4PSRegistry.json  — ABI + bytecode for deployment
 *   src/lib/contract/abi.ts                 — the ABI as a typed constant for viem/wagmi
 */
import fs from "node:fs";
import path from "node:path";
// eslint-disable-next-line @typescript-eslint/no-require-imports
const solc = require("solc");

const root = path.resolve(__dirname, "..", "..");
const source = fs.readFileSync(path.join(root, "contracts", "IP4PSRegistry.sol"), "utf8");

const input = {
  language: "Solidity",
  sources: { "IP4PSRegistry.sol": { content: source } },
  settings: {
    optimizer: { enabled: true, runs: 200 },
    viaIR: true,
    evmVersion: "cancun",
    outputSelection: { "*": { "*": ["abi", "evm.bytecode.object", "evm.deployedBytecode.object"] } },
  },
};

function findImports(importPath: string) {
  const candidates = [path.join(root, "node_modules", importPath), path.join(root, "contracts", importPath)];
  for (const c of candidates) if (fs.existsSync(c)) return { contents: fs.readFileSync(c, "utf8") };
  return { error: `Import not found: ${importPath}` };
}

const output = JSON.parse(solc.compile(JSON.stringify(input), { import: findImports }));
const errors = (output.errors ?? []) as { severity: string; formattedMessage: string }[];
for (const e of errors) console[e.severity === "error" ? "error" : "warn"](e.formattedMessage);
if (errors.some((e) => e.severity === "error")) process.exit(1);

const c = output.contracts["IP4PSRegistry.sol"]["IP4PSRegistry"];
const artifact = {
  contractName: "IP4PSRegistry",
  compiler: solc.version(),
  abi: c.abi,
  bytecode: "0x" + c.evm.bytecode.object,
  deployedBytecodeSize: c.evm.deployedBytecode.object.length / 2,
};
fs.mkdirSync(path.join(root, "contracts", "artifacts"), { recursive: true });
fs.writeFileSync(path.join(root, "contracts", "artifacts", "IP4PSRegistry.json"), JSON.stringify(artifact, null, 2));

fs.mkdirSync(path.join(root, "src", "lib", "contract"), { recursive: true });
fs.writeFileSync(
  path.join(root, "src", "lib", "contract", "abi.ts"),
  `// Generated by contracts/scripts/compile.ts — do not edit by hand.\nexport const ip4psRegistryAbi = ${JSON.stringify(c.abi, null, 2)} as const;\n`,
);
console.log(`Compiled IP4PSRegistry with ${solc.version()} — runtime size ${artifact.deployedBytecodeSize} bytes (limit 24576)`);
